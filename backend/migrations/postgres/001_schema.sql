CREATE TABLE IF NOT EXISTS categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  description TEXT,
  price NUMERIC(10,2) NOT NULL DEFAULT 0,
  category VARCHAR(255),
  barcode VARCHAR(100) UNIQUE,
  stock INTEGER NOT NULL DEFAULT 0,
  image VARCHAR(500),
  size VARCHAR(50),
  sizes JSONB,
  "categoryId" INTEGER,
  department VARCHAR(100) DEFAULT '',
  cost_price NUMERIC(10,2) DEFAULT 0,
  product_group_id INTEGER,
  variant_size VARCHAR(50),
  deleted SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_products_deleted ON products(deleted);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);

CREATE TABLE IF NOT EXISTS admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(255) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'sub',
  can_view_inventory_logs SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sales (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_id INTEGER,
  total NUMERIC(10,2) NOT NULL DEFAULT 0,
  "adminId" INTEGER,
  product_id INTEGER,
  barcode VARCHAR(255),
  quantity INTEGER,
  price NUMERIC(10,2),
  product_name VARCHAR(255),
  refunded SMALLINT NOT NULL DEFAULT 0,
  refund_type VARCHAR(50),
  customer_name VARCHAR(255),
  customer_type VARCHAR(100) DEFAULT '',
  checkout_department VARCHAR(100) DEFAULT '',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sales_receipt ON sales(receipt_id);

CREATE TABLE IF NOT EXISTS sales_backup (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER,
  barcode VARCHAR(100),
  quantity INTEGER NOT NULL DEFAULT 1,
  price NUMERIC(10,2) NOT NULL DEFAULT 0,
  total NUMERIC(10,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  product_name VARCHAR(255),
  receipt_id BIGINT,
  refunded SMALLINT NOT NULL DEFAULT 0,
  refund_type VARCHAR(20),
  "adminId" INTEGER
);
CREATE INDEX IF NOT EXISTS idx_sales_backup_receipt ON sales_backup(receipt_id);

CREATE TABLE IF NOT EXISTS sales_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_id INTEGER,
  product_id INTEGER,
  product_name VARCHAR(255) NOT NULL,
  barcode VARCHAR(100),
  customer_name VARCHAR(100),
  quantity INTEGER NOT NULL DEFAULT 1,
  price NUMERIC(10,2) NOT NULL DEFAULT 0,
  total NUMERIC(10,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sales_items_receipt ON sales_items(receipt_id);

CREATE TABLE IF NOT EXISTS restocks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL,
  quantity_added INTEGER NOT NULL,
  previous_stock INTEGER DEFAULT 0,
  new_stock INTEGER DEFAULT 0,
  reason VARCHAR(255) DEFAULT '',
  supplier VARCHAR(255),
  cost_price NUMERIC(10,2) DEFAULT 0,
  notes TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_restocks_product ON restocks(product_id);

CREATE TABLE IF NOT EXISTS inventory_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_id INTEGER,
  product_id INTEGER NOT NULL,
  product_name VARCHAR(255) NOT NULL,
  barcode VARCHAR(255),
  staff_name VARCHAR(255),
  reference VARCHAR(255),
  type VARCHAR(3) NOT NULL CHECK (type IN ('IN', 'OUT')),
  quantity INTEGER NOT NULL,
  reason VARCHAR(255) DEFAULT '',
  staff VARCHAR(100) DEFAULT 'System',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_inventory_logs_product ON inventory_logs(product_id);
CREATE INDEX IF NOT EXISTS idx_inventory_logs_created ON inventory_logs(created_at);

CREATE TABLE IF NOT EXISTS customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  full_name VARCHAR(255),
  email VARCHAR(255) UNIQUE,
  contact VARCHAR(50),
  contact_number VARCHAR(20),
  password VARCHAR(255),
  role VARCHAR(20) NOT NULL DEFAULT 'customer',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS online_orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number VARCHAR(50) NOT NULL UNIQUE,
  customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  total_amount NUMERIC(10,2) NOT NULL DEFAULT 0,
  payment_method VARCHAR(20) DEFAULT 'gcash' CHECK (payment_method IN ('gcash', 'rcbc')),
  payment_status VARCHAR(20) DEFAULT 'pending' CHECK (payment_status IN ('pending', 'verified', 'rejected')),
  order_status VARCHAR(30) DEFAULT 'pending_payment' CHECK (order_status IN ('pending_payment', 'verified', 'preparing', 'ready_for_pickup', 'completed', 'rejected')),
  reference_number VARCHAR(100),
  receipt_image VARCHAR(500),
  verified_by INTEGER,
  verified_at TIMESTAMP,
  notes TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_online_orders_customer ON online_orders(customer_id);

CREATE TABLE IF NOT EXISTS order_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES online_orders(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  product_name VARCHAR(255) NOT NULL,
  barcode VARCHAR(100),
  quantity INTEGER NOT NULL DEFAULT 1,
  price NUMERIC(10,2) NOT NULL DEFAULT 0,
  total NUMERIC(10,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items(order_id);

CREATE TABLE IF NOT EXISTS order_payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES online_orders(id) ON DELETE CASCADE,
  amount NUMERIC(10,2) NOT NULL DEFAULT 0,
  payment_method VARCHAR(50),
  reference_number VARCHAR(100),
  receipt_image VARCHAR(500),
  status VARCHAR(20) DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'rejected')),
  verified_by INTEGER,
  verified_at TIMESTAMP,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_order_payments_order ON order_payments(order_id);

CREATE TABLE IF NOT EXISTS ecom_orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  total_amount NUMERIC(10,2) NOT NULL DEFAULT 0,
  status VARCHAR(50) NOT NULL DEFAULT 'Pending Payment Verification',
  customer_full_name VARCHAR(255),
  customer_email VARCHAR(255),
  customer_contact VARCHAR(20),
  reference_number VARCHAR(255),
  payment_method VARCHAR(50),
  receipt_image VARCHAR(500),
  payment_status VARCHAR(20) NOT NULL DEFAULT 'pending',
  pickup_code VARCHAR(10) UNIQUE,
  verified_at TIMESTAMP,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ecom_orders_customer ON ecom_orders(customer_id);
CREATE INDEX IF NOT EXISTS idx_ecom_orders_status ON ecom_orders(status);

CREATE TABLE IF NOT EXISTS ecom_order_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES ecom_orders(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  product_name VARCHAR(255) NOT NULL,
  quantity INTEGER NOT NULL DEFAULT 1,
  price NUMERIC(10,2) NOT NULL DEFAULT 0,
  selected_size VARCHAR(50),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ecom_order_items_order ON ecom_order_items(order_id);

CREATE TABLE IF NOT EXISTS ecom_payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES ecom_orders(id) ON DELETE CASCADE,
  customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  receipt_image VARCHAR(500),
  reference_number VARCHAR(255),
  payment_method VARCHAR(50),
  amount NUMERIC(10,2) NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  verified_by INTEGER,
  verified_at TIMESTAMP,
  notes TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ecom_payments_order ON ecom_payments(order_id);
CREATE INDEX IF NOT EXISTS idx_ecom_payments_customer ON ecom_payments(customer_id);

CREATE TABLE IF NOT EXISTS ecom_carts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL UNIQUE REFERENCES customers(id) ON DELETE CASCADE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ecom_cart_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cart_id INTEGER NOT NULL REFERENCES ecom_carts(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  quantity INTEGER NOT NULL DEFAULT 1,
  selected_size VARCHAR(50),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ecom_cart_items_cart ON ecom_cart_items(cart_id);

CREATE TABLE IF NOT EXISTS otp_codes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  otp_code VARCHAR(6) NOT NULL,
  purpose VARCHAR(10) NOT NULL CHECK (purpose IN ('login', 'register')),
  expires_at TIMESTAMP NOT NULL,
  used SMALLINT NOT NULL DEFAULT 0,
  attempts INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_otp_email_purpose ON otp_codes(email, purpose);

CREATE TABLE IF NOT EXISTS receipt_counters (
  name VARCHAR(32) PRIMARY KEY,
  value BIGINT NOT NULL
);
INSERT INTO receipt_counters (name, value) VALUES ('pos', 1000)
ON CONFLICT (name) DO NOTHING;

CREATE OR REPLACE FUNCTION update_updated_at_column() RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER products_updated_at BEFORE UPDATE ON products
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER admins_updated_at BEFORE UPDATE ON admins
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER customers_updated_at BEFORE UPDATE ON customers
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER online_orders_updated_at BEFORE UPDATE ON online_orders
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER ecom_orders_updated_at BEFORE UPDATE ON ecom_orders
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER ecom_payments_updated_at BEFORE UPDATE ON ecom_payments
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER ecom_carts_updated_at BEFORE UPDATE ON ecom_carts
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
